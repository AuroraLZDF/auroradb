import { describe, expect, it } from 'vitest'
import { DRIVER_CAPABILITIES, capabilitiesOf, normalizeDriver } from './driver'

describe('driver capabilities', () => {
  it('默认回退到 MySQL 能力（未连接/未指定驱动时保持旧行为）', () => {
    expect(normalizeDriver(undefined)).toBe('mysql')
    expect(normalizeDriver(null)).toBe('mysql')
    expect(capabilitiesOf(undefined)).toBe(DRIVER_CAPABILITIES.mysql)
    expect(capabilitiesOf(null).prompt).toBe('mysql')
  })

  it('MySQL 保持全部能力：可写、零值日期、原生 USE / SHOW CREATE TABLE、全部 Pro 工具', () => {
    const mysql = capabilitiesOf('mysql')
    expect(mysql.editableTableData).toBe(true)
    expect(mysql.zeroDateDefaults).toBe(true)
    expect(mysql.nativeUseStatement).toBe(true)
    expect(mysql.nativeShowCreateTable).toBe(true)
    expect(mysql.formatDdl).toBe(false)
    expect(mysql.tableQualification).toBe('database')
    expect(Object.values(mysql.proTools).every(Boolean)).toBe(true)
    expect(mysql.ddlDialect).toBe('mysql')
    expect(mysql.multiStatementDdl).toBe(true)
    expect(mysql.supportsColumnPosition).toBe(true)
    expect(mysql.inlineColumnComments).toBe(true)
    expect(mysql.supportsUnsigned).toBe(true)
    expect(mysql.supportsOnUpdateTimestamp).toBe(true)
    expect(mysql.supportsVirtualColumns).toBe(true)
    expect(mysql.autoIncrementRequiresPrimaryKey).toBe(true)
    expect(mysql.databaseDesignerMode).toBe('database')
    expect(mysql.supportsDatabaseCharset).toBe(true)
    expect(mysql.monitorDialect).toBe('mysql')
    expect(mysql.supportsAllDatabaseSearch).toBe(true)
    expect(mysql.backupDialect).toBe('mysql')
    expect(mysql.dataTypes).toContain('tinyint')
    expect(mysql.dataTypes).toContain('enum')
    expect(mysql.indexTypes).toEqual(['BTREE', 'HASH', 'FULLTEXT'])
  })

  it('PostgreSQL 支持表数据保存与全部 Pro 工具（监控/备份/结构对比/全局搜索/ER 图）', () => {
    const postgres = capabilitiesOf('postgres')
    expect(postgres.editableTableData).toBe(true)
    expect(postgres.zeroDateDefaults).toBe(false)
    expect(postgres.nativeUseStatement).toBe(false)
    expect(postgres.nativeShowCreateTable).toBe(false)
    expect(postgres.formatDdl).toBe(true)
    expect(postgres.requiresDatabase).toBe(false)
    expect(postgres.tableQualification).toBe('schema')
    expect(Object.values(postgres.proTools).every(Boolean)).toBe(true)
    expect(postgres.ddlDialect).toBe('postgres')
    expect(postgres.monitorDialect).toBe('postgres')
    expect(postgres.multiStatementDdl).toBe(false)
    expect(postgres.supportsColumnPosition).toBe(false)
    expect(postgres.inlineColumnComments).toBe(false)
    expect(postgres.supportsUnsigned).toBe(false)
    expect(postgres.supportsOnUpdateTimestamp).toBe(false)
    expect(postgres.supportsVirtualColumns).toBe(false)
    expect(postgres.autoIncrementRequiresPrimaryKey).toBe(false)
    expect(postgres.databaseDesignerMode).toBe('schema')
    expect(postgres.supportsDatabaseCharset).toBe(false)
    expect(postgres.supportsAllDatabaseSearch).toBe(false)
    expect(postgres.backupDialect).toBe('postgres')
    expect(postgres.dataTypes).toContain('timestamptz')
    expect(postgres.dataTypes).toContain('bytea')
    expect(postgres.dataTypes).not.toContain('tinyint')
    expect(postgres.dataTypes).not.toContain('enum')
    expect(postgres.indexTypes).toEqual(['btree', 'hash', 'gin', 'gist', 'brin'])
  })

  it('每个驱动都有独立配置对象与默认端口', () => {
    const drivers = Object.keys(DRIVER_CAPABILITIES)
    expect(new Set(drivers.map(driver => DRIVER_CAPABILITIES[driver as keyof typeof DRIVER_CAPABILITIES])).size).toBe(drivers.length)
    expect(DRIVER_CAPABILITIES.mysql.defaultPort).toBe(3306)
    expect(DRIVER_CAPABILITIES.postgres.defaultPort).toBe(5432)
  })

  it('SQLite：文件模式、可编辑表数据、Pro 工具（P5 已支持对比/搜索/ER 图）', () => {
    const sqlite = capabilitiesOf('sqlite')
    expect(sqlite.label).toBe('SQLite')
    expect(sqlite.defaultPort).toBeNull()
    expect(sqlite.prompt).toBe('sqlite')
    expect(sqlite.identifierQuote).toBe('"')
    expect(sqlite.editableTableData).toBe(true)
    expect(sqlite.zeroDateDefaults).toBe(false)
    expect(sqlite.nativeUseStatement).toBe(false)
    expect(sqlite.nativeShowCreateTable).toBe(false)
    expect(sqlite.formatDdl).toBe(true)
    expect(sqlite.requiresDatabase).toBe(true)
    expect(sqlite.tableQualification).toBe('database')
    expect(sqlite.proTools.backup).toBe(true)
    expect(sqlite.proTools.monitor).toBe(false)
    expect(sqlite.proTools.schemaDiff).toBe(true)
    expect(sqlite.proTools.globalSearch).toBe(true)
    expect(sqlite.proTools.erDiagram).toBe(true)
    expect(sqlite.ddlDialect).toBe('mysql')
    expect(sqlite.backupDialect).toBe('sqlite')
    expect(sqlite.multiStatementDdl).toBe(true)
    expect(sqlite.supportsColumnPosition).toBe(false)
    expect(sqlite.inlineColumnComments).toBe(false)
    expect(sqlite.autoIncrementRequiresPrimaryKey).toBe(true)
    expect(sqlite.supportsDatabaseCharset).toBe(false)
    expect(sqlite.supportsAllDatabaseSearch).toBe(false)
    expect(sqlite.dataTypes).toContain('INTEGER')
    expect(sqlite.dataTypes).toContain('BLOB')
    expect(sqlite.dataTypes).not.toContain('enum')
    expect(sqlite.indexTypes).toEqual([])
  })
})
